def seed_ui_bottle_tracking_translations(user_id: int | None = None) -> None:
    """Upsert the ui_bottle_tracking admin-UI translations (idempotent)."""
    Translation.bulk_create_or_update(
        UI_BOTTLE_TRACKING_TRANSLATIONS, category=UI_BOTTLE_TRACKING_CATEGORY, user_id=user_id
    )


def main() -> None:
    app = create_app()
    with app.app_context():
        seed_ui_bottle_tracking_translations()
        total = len(UI_BOTTLE_TRACKING_TRANSLATIONS["en"])
        print(f"Seeded {total} ui_bottle_tracking translation rows (x3 languages).")


if __name__ == "__main__":
    main()
