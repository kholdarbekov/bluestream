def seed_ui_product_categories_translations(user_id: int | None = None) -> None:
    """Upsert the ui_product_categories admin-UI translations (idempotent)."""
    Translation.bulk_create_or_update(
        UI_PRODUCT_CATEGORIES_TRANSLATIONS, category=UI_PRODUCT_CATEGORIES_CATEGORY, user_id=user_id
    )


def main() -> None:
    app = create_app()
    with app.app_context():
        seed_ui_product_categories_translations()
        total = len(UI_PRODUCT_CATEGORIES_TRANSLATIONS["en"])
        print(f"Seeded {total} ui_product_categories translation rows (x3 languages).")


if __name__ == "__main__":
    main()
