def seed_ui_translations_page_translations(user_id: int | None = None) -> None:
    """Upsert the ui_translations_page admin-UI translations (idempotent)."""
    Translation.bulk_create_or_update(
        UI_TRANSLATIONS_PAGE_TRANSLATIONS, category=UI_TRANSLATIONS_PAGE_CATEGORY, user_id=user_id
    )


def main() -> None:
    app = create_app()
    with app.app_context():
        seed_ui_translations_page_translations()
        total = len(UI_TRANSLATIONS_PAGE_TRANSLATIONS["en"])
        print(f"Seeded {total} ui_translations_page translation rows (x3 languages).")


if __name__ == "__main__":
    main()
