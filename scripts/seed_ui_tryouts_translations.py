def seed_ui_tryouts_translations(user_id: int | None = None) -> None:
    """Upsert the ui_tryouts admin-UI translations (idempotent)."""
    Translation.bulk_create_or_update(
        UI_TRYOUTS_TRANSLATIONS, category=UI_TRYOUTS_CATEGORY, user_id=user_id
    )


def main() -> None:
    app = create_app()
    with app.app_context():
        seed_ui_tryouts_translations()
        total = len(UI_TRYOUTS_TRANSLATIONS["en"])
        print(f"Seeded {total} ui_tryouts translation rows (x3 languages).")


if __name__ == "__main__":
    main()
