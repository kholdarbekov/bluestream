def insert_missing(rows):
    """Adds each (key, language) that has no row; never touches an existing one, then drops the cached value of the
    added ones (a miss may have been cached as the key itself). Returns the number added."""
    added = {}
    for key, values in rows.items():
        for language, value in values.items():
            if Translation.query.filter_by(key=key, language=language).first() is None:
                db.session.add(
                    Translation(key=key, language=language, value=value, category=key.split(".")[0], is_active=True)
                )
                added.setdefault(language, {})[key] = value
    db.session.flush()
    if added:
        Translation._invalidate_translation_cache(added)
    return sum(len(v) for v in added.values())


